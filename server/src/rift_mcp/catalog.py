"""The only generator of tool listings (README table, Claude permissions, pamphlet data).

Every renderer takes the canonical document returned by ``to_document``, never ``ToolSpec``
directly, so the README, the permission list and the pamphlet cannot disagree.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from . import PROTOCOL_VERSION, __version__
from .registry import (
    CURRENT_WAVE,
    EXCLUDED,
    PROMPTS,
    RESOURCES,
    TOOLS,
    WAVE_TITLES,
    WAVES,
    ToolSpec,
    validate,
    validate_surfaces,
)

SERVER_NAME = "rift"
README_BEGIN = "<!-- tools:begin (generated by `rift-mcp tools --format md`, do not edit) -->"
README_END = "<!-- tools:end -->"


def repo_root() -> Path:
    return Path(__file__).resolve().parents[3]


def readme_path() -> Path:
    return repo_root() / "README.md"


def pamphlet_json_path() -> Path:
    return repo_root() / "docs" / "pamphlet" / "tools.json"


def _tool(t: ToolSpec) -> dict[str, Any]:
    return {
        "name": t.name,
        "wave": t.wave,
        "toolset": t.toolset,
        "risk": t.risk,
        "status": t.status,
        "annotations": {
            "readOnlyHint": t.read_only,
            "destructiveHint": t.destructive,
            "idempotentHint": t.idempotent,
        },
        "remote_op": t.remote_op,
        "origin": list(t.origin),
        "description": t.description,
    }


def to_document(tools: tuple[ToolSpec, ...] = TOOLS) -> dict[str, Any]:
    validate(tools)
    validate_surfaces()
    return {
        "server": SERVER_NAME,
        "version": __version__,
        "protocol": PROTOCOL_VERSION,
        "current_wave": CURRENT_WAVE,
        "waves": [{"id": w, "title": WAVE_TITLES[w]} for w in WAVES],
        "tools": [_tool(t) for t in tools],
        "prompts": [
            {
                "name": p.name,
                "wave": p.wave,
                "status": p.status,
                "origin": list(p.origin),
                "description": p.description,
            }
            for p in PROMPTS
        ],
        "resources": [
            {
                "name": r.name,
                "uri": r.uri,
                "wave": r.wave,
                "status": r.status,
                "origin": list(r.origin),
                "description": r.description,
            }
            for r in RESOURCES
        ],
        "excluded": [{"origin": o, "reason": why} for o, why in sorted(EXCLUDED.items())],
    }


def render_json(doc: dict[str, Any]) -> str:
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def _origin_md(origin: list[str]) -> str:
    names = [o for o in origin if o != "rift"]
    if not names:
        return "—"
    return ", ".join(f"`{o}`" for o in names)


def render_markdown(doc: dict[str, Any]) -> str:
    tools = doc["tools"]
    shipped = sum(1 for t in tools if t["status"] == "implemented")
    lines = [
        f"{len(tools)} tools in the catalogue, {shipped} shipped. `designed` tools are planned "
        "and do not run yet. Risk follows ADR-012: `auto` fixed reads, `ask` bounded side "
        "effects, `never_auto` writes and the document life cycle. Origin names the counterpart "
        "in the pyRevit MCP extension or in rvt-mcp.",
        "",
    ]
    for wave in doc["waves"]:
        rows = [t for t in tools if t["wave"] == wave["id"]]
        if not rows:
            continue
        lines += [
            f"**{wave['id']} — {wave['title']}**",
            "",
            "| Tool | Toolset | Risk | Status | Origin |",
            "|---|---|---|---|---|",
        ]
        for t in rows:
            lines.append(
                f"| `{t['name']}` | {t['toolset']} | `{t['risk']}` | {t['status']} "
                f"| {_origin_md(t['origin'])} |"
            )
        lines.append("")
    surfaces = [("prompt", p) for p in doc.get("prompts", [])] + [
        ("resource", r) for r in doc.get("resources", [])
    ]
    if surfaces:
        lines += [
            "**MCP prompts and resources**",
            "",
            "| Name | Kind | Wave | Status | Origin |",
            "|---|---|---|---|---|",
        ]
        for kind, item in surfaces:
            name = item.get("uri") or item["name"]
            lines.append(
                f"| `{name}` | {kind} | {item['wave']} | {item['status']} "
                f"| {_origin_md(item['origin'])} |"
            )
        lines.append("")
    if doc.get("excluded"):
        lines.append(
            "Not taken over on purpose: "
            + "; ".join(f"`{e['origin']}` ({e['reason']})" for e in doc["excluded"])
            + ". Whole families: ADR-027 §4 and `docs/plans/tool-catalogue/`."
        )
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def render_permissions_claude(doc: dict[str, Any]) -> str:
    """Claude Code permission rules for the shipped tools; ``never_auto`` is never allowed."""
    allow: list[str] = []
    ask: list[str] = []
    for t in doc["tools"]:
        if t["status"] != "implemented":
            continue
        rule = f"mcp__{SERVER_NAME}__{t['name']}"
        (allow if t["risk"] == "auto" else ask).append(rule)
    return json.dumps({"permissions": {"allow": allow, "ask": ask}}, indent=2) + "\n"


def permissions_path() -> Path:
    return repo_root() / "docs" / "pamphlet" / "permissions.claude.json"


def schemas_path() -> Path:
    return repo_root() / "docs" / "pamphlet" / "schemas.json"


def render_schemas(doc: dict[str, Any]) -> str:
    """Input schemas of the shipped tools, as the MCP server advertises them (M1 tranche 6).

    The schemas are taken from the built server (one source: the tool signatures), in registry
    order, with the registry's annotations next to them so that a client can check both.
    """
    import anyio

    from .server import ClientPool, build_server

    server = build_server(ClientPool(lambda _pid: _never()))
    advertised = {t.name: t for t in anyio.run(server.list_tools)}
    tools = []
    for t in doc["tools"]:
        if t["status"] != "implemented":
            continue
        mcp_tool = advertised[t["name"]]
        tools.append(
            {
                "name": t["name"],
                "risk": t["risk"],
                "annotations": t["annotations"],
                "description": mcp_tool.description,
                "inputSchema": mcp_tool.inputSchema,
            }
        )
    unexpected = sorted(set(advertised) - {t["name"] for t in tools})
    if unexpected:
        raise ValueError(f"tools advertised but not implemented in the registry: {unexpected}")
    return json.dumps({"server": SERVER_NAME, "tools": tools}, indent=2, ensure_ascii=False) + "\n"


def _never() -> Any:
    raise RuntimeError("the schema listing never talks to Revit")


def readme_with_table(readme: str, table: str) -> str:
    begin = readme.find(README_BEGIN)
    end = readme.find(README_END)
    if begin < 0 or end < begin:
        raise ValueError("README.md has no tools:begin/tools:end markers")
    return readme[: begin + len(README_BEGIN)] + "\n\n" + table + "\n" + readme[end:]


#: kind → ((format, path, renderer), …): every committed artefact generated from the registry.
def _artefacts(kind: str) -> list[tuple[str, Path, Any]]:
    if kind == "tools":
        return [("md", readme_path(), None), ("json", pamphlet_json_path(), render_json)]
    if kind == "permissions":
        return [("claude", permissions_path(), render_permissions_claude)]
    if kind == "schemas":
        return [("json", schemas_path(), render_schemas)]
    raise ValueError(kind)


def render(kind: str, fmt: str) -> str:
    doc = to_document()
    if kind == "tools":
        return render_json(doc) if fmt == "json" else render_markdown(doc)
    for f, _path, renderer in _artefacts(kind):
        if f == fmt:
            return renderer(doc)
    raise ValueError(f"{kind}: unknown format {fmt}")


def _current(doc: dict[str, Any], fmt: str, path: Path, renderer: Any) -> bool:
    if fmt == "md":
        readme = path.read_text(encoding="utf-8")
        return readme_with_table(readme, render_markdown(doc)) == readme
    return path.exists() and path.read_text(encoding="utf-8") == renderer(doc)


def check(kind: str = "tools") -> list[str]:
    """Returns the generated artefacts of ``kind`` that are out of date (empty when current)."""
    doc = to_document()
    stale: list[str] = []
    for fmt, path, renderer in _artefacts(kind):
        if not _current(doc, fmt, path, renderer):
            rel = path.relative_to(repo_root()).as_posix()
            stale.append(f"{rel} (run: rift-mcp {kind} --format {fmt} --write)")
    return stale


def write(kind: str = "tools", fmt: str = "md") -> Path:
    doc = to_document()
    for f, path, renderer in _artefacts(kind):
        if f != fmt:
            continue
        if fmt == "md":
            path.write_text(
                readme_with_table(path.read_text(encoding="utf-8"), render_markdown(doc)),
                encoding="utf-8",
                newline="\n",
            )
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(renderer(doc), encoding="utf-8", newline="\n")
        return path
    raise ValueError(f"{kind}: unknown format {fmt}")
