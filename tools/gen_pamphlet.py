SCRIPT = """
(function () {
  var buttons = document.querySelectorAll('.seg button');
  var rows = document.querySelectorAll('tr[data-risk]');
  buttons.forEach(function (b) {
    b.addEventListener('click', function () {
      buttons.forEach(function (o) { o.setAttribute('aria-pressed', o === b ? 'true' : 'false'); });
      var risk = b.getAttribute('data-filter');
      rows.forEach(function (r) { r.hidden = risk !== 'all' && r.getAttribute('data-risk') !== risk; });
    });
  });
})();
"""


def e(text: object) -> str:
    return html.escape(str(text), quote=True)


def origin_text(origin: list[str]) -> str:
    names = [o for o in origin if o != "rift"]
    return " · ".join(names) if names else "RIFT only"


def tool_row(t: dict) -> str:
    shipped = t["status"] == "implemented"
    state = "filled" if shipped else "empty"
    status = "shipped" if shipped else "designed"
    risk = t["risk"].replace("_", " ")
    if t["annotations"]["destructiveHint"]:
        risk += " · destructive"
    return (
        f'<tr data-risk="{e(t["risk"])}">'
        f'<td class="c-dot"><span class="zd-pastille" data-state="{state}" role="img" aria-label="{status}"></span></td>'
        f'<td><code>{e(t["name"])}</code></td>'
        f'<td class="c-set">{e(t["toolset"])}</td>'
        f'<td class="c-risk">{e(risk)}</td>'
        f'<td class="c-desc">{e(t["description"])}<div class="c-origin">{e(origin_text(t["origin"]))}</div></td>'
        "</tr>"
    )


def build(doc: dict) -> str:
    tools = doc["tools"]
    waves = doc["waves"]
    current = doc["current_wave"]
    shipped = sum(1 for t in tools if t["status"] == "implemented")
    by_wave = {w["id"]: [t for t in tools if t["wave"] == w["id"]] for w in waves}

    stats = []
    for w in waves:
        rows = by_wave[w["id"]]
        reads = sum(1 for t in rows if t["annotations"]["readOnlyHint"])
        stats.append(
            f'<div class="stat"><span class="zd-label">{e(w["id"])}</span>'
            f'<span class="zd-num">{len(rows)}</span>'
            f"<p>{e(w['title'])} · {reads} reads</p></div>"
        )

    road = []
    steps = [*waves, {"id": "M5", "title": "ribbon and visual identity"}]
    now_at = [s["id"] for s in steps].index(current)
    for i, w in enumerate(steps):
        state = "filled" if i < now_at else "now" if i == now_at else "empty"
        road.append(
            f'<div class="road__step"><span class="zd-pastille" data-state="{state}" aria-hidden="true"></span>'
            f'<span class="zd-label">{e(w["id"])}{" · now" if state == "now" else ""}</span>'
            f"<p>{e(w['title'])}</p></div>"
        )

    sections = []
    for w in waves:
        rows = by_wave[w["id"]]
        if not rows:
            continue
        sections.append(
            f'<section class="wave" aria-labelledby="w-{e(w["id"])}">'
            f'<span class="zd-label">{e(w["id"])} · {len(rows)} tools</span>'
            f'<h2 id="w-{e(w["id"])}">{e(w["title"])}</h2>'
            '<div class="panel"><table><thead><tr><th class="c-dot"><span class="zd-label">state</span></th>'
            '<th>tool</th><th class="c-set">toolset</th><th>risk</th><th>what it does · origin</th></tr></thead><tbody>'
            + "".join(tool_row(t) for t in rows)
            + "</tbody></table></div></section>"
        )

    ribbon_rows = "".join(
        f"<tr><td><code>{e(panel)}</code></td><td><code>{e(button)}</code></td>"
        f'<td class="c-desc">{e(action)}</td><td class="c-risk">{e(when)}</td></tr>'
        for panel, button, action, when in RIBBON
    )

    legend = "".join(
        f'<div><span class="zd-label">{e(k.replace("_", " "))}</span><p>{e(v)}</p></div>'
        for k, v in RISK_TEXT.items()
    )

    filters = "".join(
        f'<button type="button" data-filter="{k}" aria-pressed="{"true" if k == "all" else "false"}">'
        f'{e(k.replace("_", " "))}</button>'
        for k in ("all", "auto", "ask", "never_auto")
    )

    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>RIFT tool catalogue</title>
<meta name="description" content="Every RIFT MCP tool, shipped or designed, by milestone, with its risk level and origin.">
<style>{CSS}</style>
</head>
<body>
<main class="card zd-card">
  <header class="titlebar">
    <span class="wordmark">RIFT</span>
    <span class="zd-label">tool catalogue · v{e(doc["version"])} · protocol {e(doc["protocol"])}</span>
  </header>

  <section class="hero" aria-labelledby="hero-label">
    <p class="zd-num">{len(tools)}</p>
    <div class="hero__meta">
      <span class="zd-label" id="hero-label">tools in the catalogue</span>
      <p class="hero__aside">{shipped} runs today, {len(tools) - shipped} are designed and planned</p>
      <p class="hero__sub">an MCP server for Revit that keeps the guard rails on its own side · generated from the tool registry, do not edit by hand</p>
    </div>
  </section>

  <section class="stats" aria-label="tools by milestone">{"".join(stats)}</section>

  <section aria-labelledby="road-title">
    <span class="zd-label">roadmap</span>
    <h2 id="road-title">where we are</h2>
    <div class="road">{"".join(road)}</div>
  </section>

  <section aria-labelledby="legend-title">
    <div class="section-head">
      <div><span class="zd-label">risk</span><h2 id="legend-title">who decides</h2></div>
      <div class="seg" role="group" aria-label="filter tools by risk">{filters}</div>
    </div>
    <div class="legend">{legend}</div>
    <p class="note">a filled pastille is a tool that runs today · an empty one is designed and planned · risk is enforced by the server and turned into your client's permission list</p>
  </section>

  {"".join(sections)}

  <section class="wave" aria-labelledby="ribbon-title">
    <span class="zd-label">in revit</span>
    <h2 id="ribbon-title">the RIFT panel in the NORN tab</h2>
    <div class="panel"><table><thead><tr><th>group</th><th>button</th><th>what it does</th><th>when</th></tr></thead>
    <tbody>{ribbon_rows}</tbody></table></div>
    <p class="note">RIFT ships as one panel of NORN, the ribbon tab shared by the maintainer's suite of revit plugins · the activity card shows each call and its outcome in a corner of revit, without taking focus</p>
  </section>

  <footer class="footer">
    <p class="note">origins name the counterpart tool in <a href="https://github.com/bimwright/rvt-mcp">rvt-mcp</a> (apache-2.0) or in the <a href="https://github.com/mcp-servers-for-revit/mcp-server-for-revit-python">pyrevit mcp extension</a> (mit) · pyrevit itself is a clean-room specification only</p>
    <span class="zd-label">apache-2.0</span>
  </footer>
</main>
<script>{SCRIPT}</script>
</body>
</html>
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if index.html is stale")
    args = parser.parse_args(argv)
    page = build(json.loads(SOURCE.read_text(encoding="utf-8")))
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != page:
            print("stale: docs/pamphlet/index.html (run: python tools/gen_pamphlet.py)", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(page, encoding="utf-8", newline="\n")
    print(f"written: {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
